"""Generate firmware/main/calib_params.h from calib.yaml (+ optional noise.yaml and NavConfig overrides).

  python tools/gen_calib_header.py calib.yaml --noise noise.yaml --config '{"use_line": 0}'
Never type calibration constants by hand.
"""
import argparse, json, os, sys
import numpy as np, yaml
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from nav.calib import CalibParams

ap = argparse.ArgumentParser()
ap.add_argument("calib")
ap.add_argument("--noise", default=None)
ap.add_argument("--config", default="{}", help="JSON of nav_config_t fields to override")
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                              "firmware", "main", "calib_params.h"))
a = ap.parse_args()
cp = CalibParams.from_yaml(a.calib)
f = lambda x: f"{float(x):.9e}f"          # always has a decimal point: valid C float literal
L = ["/* GENERATED by tools/gen_calib_header.py. Do not edit by hand. */",
     f"/* source: {os.path.abspath(a.calib)} */", "#ifndef CALIB_PARAMS_H", "#define CALIB_PARAMS_H", '#include "nav.h"',
     "static inline void calib_params_load(nav_calib_t *c, nav_config_t *cfg)", "{"]
for name, M in (("Ta", cp.Ta), ("Tg", cp.Tg)):
    for i in range(3):
        for j in range(3):
            L.append(f"    c->{name}[{i}][{j}] = {f(M[i, j])};")
for name, v in (("Ka", np.diag(cp.Ka)), ("Kg", np.diag(cp.Kg)), ("ba", cp.ba), ("bg", cp.bg)):
    for i in range(3):
        L.append(f"    c->{name}[{i}] = {f(v[i])};")
over = json.loads(a.config)
if a.noise:
    with open(a.noise) as fh:
        n = yaml.safe_load(fh)
    over.setdefault("Na", n["Na"]); over.setdefault("Ng", n["Ng"])
if "g" in cp.info:
    over.setdefault("g", cp.info["g"])
for k, v in over.items():
    L.append(f"    cfg->{k} = {f(v) if isinstance(v, float) else int(v)};")
if not over:
    L.append("    (void)cfg;")
L += ["}", "#endif", ""]
with open(a.out, "w") as fh:
    fh.write("\n".join(L))
print("wrote", a.out)
